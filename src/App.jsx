let audioCtx = null;
const playUISound = () => {
  if (typeof window === 'undefined') return;
  try {
    if (!audioCtx) {
      const AudioContext = window.AudioContext || window.webkitAudioContext;
      audioCtx = new AudioContext();
    }
    if (audioCtx.state === 'suspended') audioCtx.resume();
    const oscillator = audioCtx.createOscillator();
    const gainNode = audioCtx.createGain();
    oscillator.type = 'sine';
    oscillator.frequency.setValueAtTime(600, audioCtx.currentTime);
    oscillator.frequency.exponentialRampToValueAtTime(1200, audioCtx.currentTime + 0.05);
    gainNode.gain.setValueAtTime(0.12, audioCtx.currentTime);
    gainNode.gain.exponentialRampToValueAtTime(0.01, audioCtx.currentTime + 0.05);
    oscillator.connect(gainNode);
    gainNode.connect(audioCtx.destination);
    oscillator.start();
    oscillator.stop(audioCtx.currentTime + 0.05);
  } catch (e) {
    console.warn('Web Audio API not supported', e);
  }
};

const Text3D = ({
  as: Component = 'span',
  children,
  className = '',
  depth = 5,
  gradient = null,
  color = 'text-amber-50',
  shadowColor = '#451a03',
  isMobile = false
}) => {
  const activeDepth = isMobile ? Math.max(1, Math.floor(depth / 1.5)) : depth;
  const shadow = Array.from({ length: activeDepth })
    .map((_, i) => `${i + 1}px ${i + 1}px 0px ${shadowColor}`)
    .join(', ');

  return (
    <Component
      className={`relative ${
        Component === 'span' ? 'inline-block' : 'block'
      } ${className} group cursor-default`}
    >
      <span
        aria-hidden="true"
        className="absolute inset-0 pointer-events-none transition-transform duration-300 group-hover:-translate-x-0.5 group-hover:-translate-y-0.5"
        style={{ color: 'transparent', textShadow: shadow, zIndex: -1 }}
      >
        {children}
      </span>
      <span
        className={`relative z-10 block transition-transform duration-300 group-hover:-translate-x-0.5 group-hover:-translate-y-0.5 ${
          gradient ? `bg-clip-text text-transparent bg-linear-to-r ${gradient}` : color
        }`}
      >
        {children}
      </span>
    </Component>
  );
};

